-- Количество ПОЗИЦИЙ внутри бокса (например "суп, второе, компот" = 3),
-- в отличие от quantity — это остаток на складе (сколько боксов ещё можно
-- купить). На карточке предложения бейдж с пакетом показывает именно
-- items_count, а не остаток.
ALTER TABLE products
  ADD COLUMN IF NOT EXISTS items_count INT NOT NULL DEFAULT 1;
